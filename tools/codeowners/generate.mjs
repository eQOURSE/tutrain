import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const codeownersRelativePath = '.github/CODEOWNERS';
const ownershipRelativePath = 'docs/contracts/ownership.json';
const mappingPattern = /^# owner (\w+) = (@\S+)$/u;

function read(relativePath) {
  return readFileSync(path.join(repositoryRoot, relativePath), 'utf8');
}

function ownerMappings(codeowners) {
  const mappings = new Map();
  for (const line of codeowners.split(/\r?\n/u)) {
    const match = line.match(mappingPattern);
    if (match) mappings.set(match[1], match[2]);
  }
  if (mappings.size === 0) throw new Error(`No owner mappings found in ${codeownersRelativePath}`);
  return mappings;
}

function ownerHandles(ownerNames, mappings) {
  const handles = [];
  for (const ownerName of ownerNames) {
    const handle = mappings.get(ownerName);
    if (!handle) throw new Error(`No CODEOWNERS mapping for owner ${ownerName}`);
    if (!handles.includes(handle)) handles.push(handle);
  }
  return handles;
}

function ownersFor(entry, moduleOwner, mappings) {
  if (entry.owner === 'module' && !moduleOwner) throw new Error('Module-scoped ownership requires a module owner');
  const primaryOwner = entry.owner === 'module' ? moduleOwner : entry.owner;
  const ownerNames = primaryOwner === 'shared' || primaryOwner === 'generated' ? entry.reviewers : [primaryOwner, ...entry.reviewers];
  return ownerHandles([...new Set(ownerNames)], mappings);
}

function anchoredPath(ownershipPath) {
  const normalized = ownershipPath.replace(/^\/+|\/+$/gu, '');
  const basename = path.posix.basename(normalized);
  const directory = ownershipPath.endsWith('/') || !basename.includes('.');
  return `/${normalized}${directory ? '/' : ''}`;
}

function pathSegments(pattern) {
  return pattern.slice(1).split('/').filter(Boolean).length;
}

export function generateCodeowners(codeowners, ownership) {
  const mappings = ownerMappings(codeowners);
  const entries = [];
  let sequence = 0;
  const add = (ownershipPath, owners) => {
    entries.push({ pattern: anchoredPath(ownershipPath), owners, sequence });
    sequence += 1;
  };

  for (const [ownershipPath, entry] of Object.entries(ownership.paths)) {
    if (ownershipPath.includes('<module>')) {
      for (const [moduleName, module] of Object.entries(ownership.modules)) {
        add(ownershipPath.replaceAll('<module>', moduleName), ownersFor(entry, module.owner, mappings));
      }
    } else {
      add(ownershipPath, ownersFor(entry, undefined, mappings));
    }
  }

  for (const module of Object.values(ownership.modules)) {
    add(module.contracts_path, ownerHandles([module.owner], mappings));
  }

  entries.sort((left, right) => pathSegments(left.pattern) - pathSegments(right.pattern) || left.sequence - right.sequence);
  const header = [
    '# Generated by pnpm codeowners from docs/contracts/ownership.json; do not edit by hand.',
    ...codeowners.split(/\r?\n/u).filter((line) => mappingPattern.test(line)),
  ];
  return `${header.join('\n')}\n\n${entries.map(({ pattern, owners }) => `${pattern} ${owners.join(' ')}`).join('\n')}\n`;
}

function main() {
  const current = existsSync(path.join(repositoryRoot, codeownersRelativePath)) ? read(codeownersRelativePath) : '';
  const generated = generateCodeowners(current, JSON.parse(read(ownershipRelativePath)));
  if (process.argv.includes('--check')) {
    if (current !== generated) {
      process.stderr.write(`${codeownersRelativePath} is out of date; run pnpm codeowners\n`);
      process.exitCode = 1;
    }
    return;
  }
  writeFileSync(path.join(repositoryRoot, codeownersRelativePath), generated);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
